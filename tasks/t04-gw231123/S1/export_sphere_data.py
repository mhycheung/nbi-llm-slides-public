#!/usr/bin/env python3
"""Extract the slide's data from the GW231123 NRSur7dq4 sphere visualizer page.

Usage: export_sphere_data.py <gw231123_nrsur7dq4_sphere.html> <output .js>
Reads the page's embedded arrays (maximum-likelihood sample of the NRSur7dq4 posterior, 2500 tiles);
computes nothing new. Keeps the animation frames with t <= T_MAX, where the strain has not yet died
away, tiles at least MIN_SEP apart, the Voronoi cell of each kept tile on the sphere (the slide fills each
cell with one gray level), and the whitened traces of both detectors. Prints the checks the slide relies on.
"""
import base64, json, re, sys
import numpy as np
from scipy.spatial import SphericalVoronoi

T_MAX = 0.06   # s after the peak; the ringdown is gone by then
MIN_SEP = 5.8   # deg, between kept tiles of the source's 2500; every third tile instead leaves visible arcs and gaps


def even_tiles(min_sep, fixed, x):
    """Indices, ascending, of tiles at least min_sep [deg] apart, over the unit vectors x; includes tile fixed.
    Goes outward from tile fixed along the source's spiral and keeps each tile far enough from those kept."""
    keep, c = [fixed], np.cos(np.radians(min_sep))
    for i in sorted(range(len(x)), key=lambda i: abs(i - fixed)):
        if (x[keep] @ x[i]).max() < c:
            keep.append(i)
    return np.sort(keep)


def const(page, name):
    m = re.search(r"const %s = (.*?);\n" % name, page, re.S)
    return json.loads(m.group(1)) if m.group(1)[0] in "[{" else m.group(1).strip('"')


page = open(sys.argv[1]).read()
n_tiles, n_anim = int(const(page, "nTiles")), int(const(page, "nAnimT"))
n_det = int(const(page, "nDetectorT"))
max_l = int(const(page, "maxLTile"))
th, ph = np.array(const(page, "thetas")), np.array(const(page, "phis"))
t_anim, t_det = np.array(const(page, "sourceAnimTime")), np.array(const(page, "detectorTime"))
refs = const(page, "references")
anim = np.frombuffer(base64.b64decode(const(page, "sourceAnimB64")), dtype="<i2").reshape(n_anim, n_tiles, 2)
det = np.frombuffer(base64.b64decode(const(page, "detectorB64")), dtype="<f4").reshape(n_tiles, n_det, 2)

keep = t_anim <= T_MAX
unit = np.c_[np.sin(th) * np.cos(ph), np.sin(th) * np.sin(ph), np.cos(th)]
tiles = even_tiles(MIN_SEP, max_l, unit)
out_frames = anim[keep][:, tiles].astype("<i2")
sep = unit[tiles] @ unit[tiles].T
np.fill_diagonal(sep, -1)
print("tiles kept", len(tiles), "nearest-neighbour separation [deg] min, median, max",
      np.degrees(np.arccos(sep.max(1))).min(), np.median(np.degrees(np.arccos(sep.max(1)))),
      np.degrees(np.arccos(sep.max(1))).max())
amp = np.hypot(anim[..., 0], anim[..., 1]) / 32767
print("frames kept", keep.sum(), "of", n_anim, "dt [ms]", 1e3 * np.median(np.diff(t_anim)))
print("|h| max over everything", amp.max(), "over tiles, by time (s, max |h|):")
for i in range(0, n_anim, 30):
    print("  %+.3f  %.3f" % (t_anim[i], amp[i].max()))
print("|h| max dropped frames", amp[~keep].max())
print("max-likelihood tile", max_l, "theta, phi [deg]", np.degrees(th[max_l]), np.degrees(ph[max_l]))
for k, ifo in enumerate(["H1", "L1"]):
    a, b = det[max_l, :, k], np.array(refs["maxl_detector"][ifo])
    print(ifo, "tile model vs bilby ML: correlation %.5f, rms ratio %.4f" % (np.corrcoef(a, b)[0, 1], a.std() / b.std()))

vor = SphericalVoronoi(unit[tiles])
vor.sort_vertices_of_regions()
print("cells", len(vor.regions), "vertices", len(vor.vertices), "total area / 4 pi",
      vor.calculate_areas().sum() / (4 * np.pi), "vertices per cell min, max",
      min(map(len, vor.regions)), max(map(len, vor.regions)))


def r(x, nd=3):
    return [round(float(v), nd) for v in x]


traces = {}
for ifo in ["H1", "L1"]:
    w, band = refs["whitened_data"][ifo], refs["nrsur_band"][ifo]
    traces[ifo] = {"data": r(w["strain"]), "lower": r(band["lower"]), "upper": r(band["upper"]),
                   "ml": r(refs["maxl_detector"][ifo])}
    print(ifo, "same times as detectorTime:", np.allclose(w["time"], t_det))

# Short pieces: the scanners of `opsci publish check` take time quadratic in the length of one run.
def chunks(s, n=1000):
    return [s[i:i + n] for i in range(0, len(s), n)]


data = {"nTiles": len(tiles), "nFrames": int(keep.sum()), "maxL": int(np.searchsorted(tiles, max_l)),
        "theta": r(th[tiles], 5), "phi": r(ph[tiles], 5),
        "verts": r(vor.vertices.ravel(), 4), "cells": [[int(v) for v in c] for c in vor.regions],
        "tFrames": r(t_anim[keep], 5), "tTrace": r(t_det, 5), "traces": traces,
        "frames": chunks(base64.urlsafe_b64encode(out_frames.tobytes()).decode())}
with open(sys.argv[2], "w") as f:
    f.write("// GW231123 NRSur7dq4 maximum-likelihood sample: h_+, h_x at %d of %d sphere tiles, and whitened traces.\n"
            "// Generated by tasks/t04-gw231123/S1/export_sphere_data.py. Do not edit.\n"
            "// verts: Voronoi vertices of the tiles, x y z, flat; cells: each tile's vertices, in order round the cell.\n"
            "// frames: Int16, little endian, (frame, tile, 2), scale 1/32767, URL-safe base64 in pieces of 1000 characters. t in s from the peak.\n"
            "window.gw231123_data = " % (len(tiles), n_tiles) + json.dumps(data, separators=(",", ":")) + ";\n")
print("wrote", sys.argv[2])
